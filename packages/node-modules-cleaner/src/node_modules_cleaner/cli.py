from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Literal

if TYPE_CHECKING:
    from collections.abc import Sequence
    from typing import TextIO


ResultStatus = Literal["removed", "would-remove", "failed"]
RM_RF_PLATFORMS = {"darwin", "linux"}


@dataclass(frozen=True, slots=True)
class CleanResult:
    path: Path
    status: ResultStatus
    detail: str = ""


def find_node_modules(root: Path) -> list[Path]:
    resolved_root = root.resolve(strict=True)
    if resolved_root.name == "node_modules":
        return [resolved_root]

    matches: list[Path] = []

    for current_root, dirnames, _filenames in os.walk(resolved_root, followlinks=False):
        if "node_modules" not in dirnames:
            continue

        matched = Path(current_root) / "node_modules"
        matches.append(matched)
        dirnames.remove("node_modules")

    return matches


def remove_with_rm_rf(path: Path) -> None:
    executable = shutil.which("rm")
    if executable is None:
        msg = "rm command not found"
        raise FileNotFoundError(msg)

    subprocess.run(  # noqa: S603
        [executable, "-rf", str(path.absolute())],
        check=True,
    )


def remove_with_python(path: Path) -> None:
    if path.is_symlink():
        path.unlink()
        return
    shutil.rmtree(path)


def remove_path(path: Path, *, platform: str | None = None) -> None:
    resolved_platform = sys.platform if platform is None else platform
    if resolved_platform in RM_RF_PLATFORMS:
        remove_with_rm_rf(path)
        return
    remove_with_python(path)


def remove_node_modules(paths: Sequence[Path], *, dry_run: bool = False) -> list[CleanResult]:
    results: list[CleanResult] = []
    for path in paths:
        if dry_run:
            results.append(CleanResult(path, "would-remove"))
            continue

        try:
            remove_path(path)
        except (OSError, subprocess.CalledProcessError) as exc:
            results.append(CleanResult(path, "failed", str(exc)))
            continue

        results.append(CleanResult(path, "removed"))

    return results


def clean_node_modules(root: Path, *, dry_run: bool = False) -> list[CleanResult]:
    return remove_node_modules(find_node_modules(root), dry_run=dry_run)


def write_results(results: Sequence[CleanResult], output: TextIO) -> None:
    if not results:
        output.write("No node_modules directories found.\n")
        return

    for result in results:
        if result.status == "removed":
            output.write(f"[REMOVED] {result.path}\n")
        elif result.status == "would-remove":
            output.write(f"[DRY-RUN] {result.path}\n")
        else:
            output.write(f"[FAILED] {result.path}: {result.detail}\n")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="node-modules-cleaner",
        description="Recursively delete node_modules directories under a target directory.",
    )
    parser.add_argument("directory", type=Path, help="Directory to scan recursively.")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print matched directories without deleting them.",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    root = args.directory.expanduser()

    if not root.exists():
        sys.stderr.write(f"Directory does not exist: {root}\n")
        return 2
    if not root.is_dir():
        sys.stderr.write(f"Not a directory: {root}\n")
        return 2

    results = clean_node_modules(root, dry_run=args.dry_run)
    write_results(results, sys.stdout)
    return 1 if any(result.status == "failed" for result in results) else 0
