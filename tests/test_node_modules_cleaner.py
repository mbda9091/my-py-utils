from __future__ import annotations

import io
from typing import TYPE_CHECKING
from unittest.mock import Mock

from node_modules_cleaner.cli import (
    CleanResult,
    clean_node_modules,
    find_node_modules,
    main,
    remove_node_modules,
    remove_path,
    write_results,
)

if TYPE_CHECKING:
    from pathlib import Path

    import pytest

EXIT_USAGE = 2


def test_find_node_modules_recursively_and_prunes_matches(tmp_path: Path) -> None:
    root_node_modules = tmp_path / "app/node_modules"
    nested_under_root_node_modules = root_node_modules / "pkg/node_modules"
    workspace_node_modules = tmp_path / "packages/tool/node_modules"
    root_node_modules.mkdir(parents=True)
    nested_under_root_node_modules.mkdir(parents=True)
    workspace_node_modules.mkdir(parents=True)

    assert find_node_modules(tmp_path) == [
        root_node_modules.resolve(),
        workspace_node_modules.resolve(),
    ]


def test_find_node_modules_includes_root_when_root_is_node_modules(tmp_path: Path) -> None:
    node_modules = tmp_path / "node_modules"
    node_modules.mkdir()

    assert find_node_modules(node_modules) == [node_modules.resolve()]


def test_clean_node_modules_deletes_matches(tmp_path: Path) -> None:
    first = tmp_path / "app/node_modules"
    second = tmp_path / "nested/package/node_modules"
    keep = tmp_path / "app/src"
    first.mkdir(parents=True)
    second.mkdir(parents=True)
    keep.mkdir(parents=True)

    results = clean_node_modules(tmp_path)

    assert results == [
        CleanResult(first.resolve(), "removed"),
        CleanResult(second.resolve(), "removed"),
    ]
    assert not first.exists()
    assert not second.exists()
    assert keep.exists()


def test_clean_node_modules_dry_run_keeps_matches(tmp_path: Path) -> None:
    node_modules = tmp_path / "app/node_modules"
    node_modules.mkdir(parents=True)

    results = clean_node_modules(tmp_path, dry_run=True)

    assert results == [CleanResult(node_modules.resolve(), "would-remove")]
    assert node_modules.exists()


def test_clean_node_modules_unlinks_symlink_without_deleting_target(tmp_path: Path) -> None:
    target = tmp_path / "target"
    node_modules = tmp_path / "app/node_modules"
    target.mkdir()
    node_modules.parent.mkdir()
    node_modules.symlink_to(target, target_is_directory=True)

    results = clean_node_modules(tmp_path)

    assert results == [CleanResult(node_modules, "removed")]
    assert not node_modules.exists()
    assert target.exists()


def test_remove_path_uses_rm_rf_on_linux(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    node_modules = tmp_path / "node_modules"
    node_modules.mkdir()
    run_mock = Mock()
    monkeypatch.setattr("shutil.which", Mock(return_value="/bin/rm"))
    monkeypatch.setattr("subprocess.run", run_mock)

    remove_path(node_modules, platform="linux")

    run_mock.assert_called_once_with(
        ["/bin/rm", "-rf", str(node_modules.absolute())],
        check=True,
    )


def test_remove_path_uses_python_on_other_platforms(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    node_modules = tmp_path / "node_modules"
    node_modules.mkdir()
    rmtree_mock = Mock()
    monkeypatch.setattr("shutil.rmtree", rmtree_mock)

    remove_path(node_modules, platform="win32")

    rmtree_mock.assert_called_once_with(node_modules)


def test_remove_node_modules_reports_failure(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    node_modules = tmp_path / "node_modules"
    node_modules.mkdir()
    remove_mock = Mock(side_effect=OSError("permission denied"))
    monkeypatch.setattr("node_modules_cleaner.cli.remove_path", remove_mock)

    results = remove_node_modules([node_modules])

    assert results == [CleanResult(node_modules, "failed", "permission denied")]
    assert node_modules.exists()


def test_write_results_reports_empty_result() -> None:
    output = io.StringIO()

    write_results([], output)

    assert output.getvalue() == "No node_modules directories found.\n"


def test_main_rejects_missing_directory(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
) -> None:
    code = main([str(tmp_path / "missing")])

    captured = capsys.readouterr()
    assert code == EXIT_USAGE
    assert "Directory does not exist:" in captured.err
